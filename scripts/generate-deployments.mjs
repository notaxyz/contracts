import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const deploymentsDir = path.join(rootDir, "deployments");
const generatedPath = path.join(rootDir, "package/src/deployments.generated.ts");

function isExampleFile(fileName) {
  return fileName.startsWith("example.") || fileName.includes(".example.");
}

const deployments = [];
const files = (await readdir(deploymentsDir))
  .filter((fileName) => fileName.endsWith(".json"))
  .filter((fileName) => !isExampleFile(fileName))
  .sort();

for (const fileName of files) {
  const deployment = JSON.parse(await readFile(path.join(deploymentsDir, fileName), "utf8"));
  deployments.push([deployment.chainId, deployment]);
}

deployments.sort(([leftChainId], [rightChainId]) => leftChainId - rightChainId);

const deploymentMap = Object.fromEntries(deployments);
const source = `// This file is generated by scripts/generate-deployments.mjs.
// Do not edit it manually.

import type { RevealDeployment } from "./types.js";

export const deployments = ${JSON.stringify(deploymentMap, null, 2)} as const satisfies Record<number, RevealDeployment>;
`;

await writeFile(generatedPath, source, "utf8");

console.log(`Wrote package/src/deployments.generated.ts with ${deployments.length} deployments.`);
